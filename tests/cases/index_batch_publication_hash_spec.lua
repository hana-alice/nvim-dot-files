local t = require("tests.harness")
t.bootstrap()

local names = require("ue.index.shard_name")
local bit = require("bit")

t.describe("index_batch_publication clangd shard filename", function()
  -- Recorded from real clangd 22.1.5 output; no fixture files need exist here.
  local root = [[F:\shard-name-fixture\src\]]
  for _, sample in ipairs({
    { "back", "5EE9A79030B53F35" },
    { "fwd", "A49E084CCDE371B7" },
    { "trig", "D37F44C68CCC580A" },
  }) do
    t.it("matches real clangd " .. sample[1] .. " shard", function()
      local path = root .. sample[1] .. ".cpp"
      local expected = sample[1] .. ".cpp." .. sample[2] .. ".idx"
      t.assert_eq(names.for_path(path), expected)
      t.assert_eq(names.for_path((path:gsub("\\", "/"))), expected)
    end)
  end

  t.it("distinguishes same basename in different directories and preserves case", function()
    t.assert_true(names.for_path([[C:\one\Module.cpp]]) ~= names.for_path([[C:\two\Module.cpp]]))
    t.assert_true(names.for_path([[C:\one\Module.cpp]]) ~= names.for_path([[C:\ONE\Module.cpp]]))
  end)

  t.it("preserves CDB case spelling without consulting realpath", function()
    local realpath = vim.uv.fs_realpath
    vim.uv.fs_realpath = function() error("pure filename function must not inspect the filesystem") end
    local ok, err = pcall(function()
      local lower = [[C:\fixture\sub\casefile.cpp]]
      local upper = [[C:\fixture\Sub\CaseFile.cpp]]
      t.assert_eq(names.for_path(lower), "casefile.cpp." .. names.digest(lower) .. ".idx")
      t.assert_eq(names.for_path(upper), "CaseFile.cpp." .. names.digest(upper) .. ".idx")
      t.assert_true(names.for_path(lower) ~= names.for_path(upper))
    end)
    vim.uv.fs_realpath = realpath
    if not ok then error(err) end
  end)

  t.it("rejects relative paths instead of guessing a cache key", function()
    t.assert_eq(pcall(names.for_path, "Module.cpp"), false)
    t.assert_eq(pcall(names.for_path, "C:Module.cpp"), false)
    t.assert_eq(pcall(names.for_path, "C:\\"), false)
    t.assert_eq(pcall(names.for_path, "C:\\one\0.cpp"), false)
  end)

  t.it("converts UNC separators and leaves POSIX absolute paths intact", function()
    t.assert_eq(names.for_path("//server/share/Module.cpp"), names.for_path([[\\server\share\Module.cpp]]))
    local path = "/one/Module.cpp"
    t.assert_eq(names.for_path(path), "Module.cpp." .. names.digest(path) .. ".idx")
  end)

  -- Independent upstream XXH3 vectors, seed=0; buffer generated by
  -- XSUM_fillTestBuffer in xxHash v0.8.3 cli/xsum_sanity_check.c.
  -- Values: https://github.com/Cyan4973/xxHash/blob/v0.8.3/tests/sanity_test_vectors.h
  local chunks, state = {}, 2654435761ULL
  for i = 1, 2048 do
    chunks[i] = string.char(tonumber(bit.rshift(state, 56)))
    state = state * 11400714785074694797ULL
  end
  local buffer = table.concat(chunks)
  local vectors = {
    { 0, "2D06800538D394C2" }, { 1, "C44BDFF4074EECDB" },
    { 3, "54247382A8D6B94D" }, { 4, "E5DC74BC51848A51" },
    { 8, "24CCC9ACAA9F65E4" }, { 9, "14D5001C15DD3F2B" },
    { 16, "981B17D36C7498C9" }, { 17, "796F5ACD3A60F862" },
    { 32, "9FEADDBDBF57EED3" }, { 33, "ABFB2D081B400A10" },
    { 64, "9CB48487720EC49D" }, { 65, "FD81AAC4BEBC3883" },
    { 96, "935A769A7F94776F" }, { 97, "CA4CA268FD3C3A6C" },
    { 128, "FCFF24126754D861" }, { 129, "98F1B0A679A2CA29" },
    { 239, "16CE2B9D3B28805D" }, { 240, "81C3C2B67F568CCF" },
    { 241, "C5A639ECD2030E5E" }, { 1023, "87A8F7B2F2E22496" },
    { 1024, "DD85C9B5C1109C5C" }, { 1025, "D870C0FA13211C6A" },
    { 2048, "DD59E2C3A5F038E0" },
  }
  for _, vector in ipairs(vectors) do
    t.it("matches upstream seed-zero vector at length " .. vector[1], function()
      local bytes = {}
      for i = #vector[2] - 1, 1, -2 do bytes[#bytes + 1] = vector[2]:sub(i, i + 1) end
      t.assert_eq(names.digest(buffer:sub(1, vector[1])), table.concat(bytes))
    end)
  end
end)
